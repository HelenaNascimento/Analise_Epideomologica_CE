CREATE VIEW [dbo].[DASH_TIMESTRAL_VXPRODUTOS] AS
SELECT 
	distinct
	CODIGO,
	Descri,
	SUM(QTD_VENDAS) AS QTD_VENDAS,
	SUM(VLR_VENDA) AS VLR_VENDAS,
	SUM(M_VENDAS) as M_VENDAS,
	dias,
	Mes,
	Ano
FROM [VW_TIMESTRAL_TOPPRODUTOS]

group by 
	CODIGO,
	Descri,
	dias,
	Mes,
	Ano
GO


