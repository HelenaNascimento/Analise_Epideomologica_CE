create view [dbo].[DASH_TIMESTRAL_VXFABRICANTE] as

SELECT 
	distinct
	CODIGO,
	FANTASIA,
	SUM(QTD_VENDAS) AS QTD_VENDAS,
	SUM(VLR_VENDA) AS VLR_VENDAS,
	SUM(M_VENDAS) as M_VENDAS,
	Ano,
	Mes
FROM VW_TIMESTRAL_VXFABRICANTE

group by 
	CODIGO,
	FANTASIA,
	Ano,
	Mes
GO


